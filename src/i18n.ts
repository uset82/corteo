export type Language = 'es' | 'en';

let currentLanguage: Language = 'es'; // Spanish by default

export function setLanguage(lang: Language) {
  currentLanguage = lang;
  if (typeof window !== 'undefined') {
    localStorage.setItem('openchatcut-language', lang);
  }
}

export function getLanguage(): Language {
  if (typeof window !== 'undefined') {
    const stored = localStorage.getItem('openchatcut-language');
    if (stored === 'es' || stored === 'en') return stored;
  }
  return currentLanguage;
}

export function t(key: keyof typeof translations.es): string {
  const lang = getLanguage();
  return translations[lang][key] || translations.en[key] || key;
}

// Initialize language from localStorage
if (typeof window !== 'undefined') {
  currentLanguage = getLanguage();
}
